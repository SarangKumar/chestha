/**
 * Writes apps/web/public/backgrounds/catalog.json from whatever image files are
 * in that folder.
 *
 * A browser cannot list a directory, so the picker in Settings needs an index to
 * read. Generating it keeps the workflow to "drop a file in, run this" rather
 * than asking anyone to hand-edit JSON.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../apps/web/public/backgrounds/', import.meta.url));
const IMAGE = /\.(jpe?g|png|webp|avif|gif|svg)$/i;

const files = readdirSync(dir).filter((name) => IMAGE.test(name)).sort();

writeFileSync(
  `${dir}catalog.json`,
  `${JSON.stringify({
    comment: 'Generated by tools/build-backgrounds.mjs. Drop images in this folder and re-run `npm run backgrounds`.',
    images: files,
  }, null, 2)}\n`,
);

console.log(files.length
  ? `Indexed ${files.length} background image(s):\n${files.map((f) => `  ${f}`).join('\n')}`
  : 'No background images found. Drop an image in apps/web/public/backgrounds/ and re-run.');
